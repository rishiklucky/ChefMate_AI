import React, { useState, useEffect } from 'react';
import { useNavigate, Link } from 'react-router-dom';
import { useRecipe } from '../context/RecipeContext';
import { useAuth } from '../context/AuthContext';
import { Clock, ExternalLink, LogIn, Lock, Users } from 'lucide-react';

export default function HistoryPage() {
  const navigate = useNavigate();
  const { isAuthenticated } = useAuth();
  const { recipeHistory, fetchRecipeHistory } = useRecipe();
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const load = async () => {
      if (isAuthenticated) {
        setLoading(true);
        await fetchRecipeHistory();
        setLoading(false);
      } else {
        setLoading(false);
      }
    };
    load();
  }, [isAuthenticated]);

  if (!isAuthenticated) {
    return (
      <div className="w-100 min-vh-100 d-flex align-items-center justify-content-center py-5 px-3">
        <div className="card-chefmate p-4 p-md-5 rounded-5 shadow-luxury border text-center max-w-md w-100" style={{ borderColor: 'rgba(234, 88, 12, 0.2)' }}>
          <div className="p-3 rounded-circle bg-danger-subtle text-danger d-inline-flex mb-3 shadow-xs">
            <Lock size={36} style={{ color: '#ea580c' }} />
          </div>
          <h3 className="font-display fw-bold text-dark mb-2">Sign In Required</h3>
          <p className="text-muted text-sm mb-4">
            Cooking history tracks your last 5 generated recipes strictly for your account. Please sign in or register to view your cooking history.
          </p>
          <div className="d-flex flex-column gap-2">
            <Link to="/login?redirect=%2Fhistory" className="btn btn-primary-chef w-100 py-2.5 rounded-4 font-display fw-bold d-flex align-items-center justify-content-center gap-2">
              <LogIn size={18} />
              <span>Sign In</span>
            </Link>
            <Link to="/register?redirect=%2Fhistory" className="btn btn-light border w-100 py-2.5 rounded-4 font-label fw-semibold text-muted">
              Create Account
            </Link>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="w-100 min-vh-100 pt-4 pb-5">
      <div className="container px-3 px-lg-5">

        {/* Header */}
        <div className="mb-4">
          <div className="d-flex align-items-center gap-2 mb-1">
            <Clock size={24} className="text-chef-orange" />
            <h2 className="font-display fw-bold text-dark m-0">Cooking History</h2>
            <span className="badge rounded-pill px-3 py-1.5 text-xs fw-bold ms-1" style={{ backgroundColor: 'rgba(234, 88, 12, 0.12)', color: '#ea580c', border: '1px solid rgba(234, 88, 12, 0.3)' }}>
              Last 5 Recipes
            </span>
          </div>
          <p className="text-muted text-sm m-0">Recent cooking guides generated by your AI chef assistant (stores up to 5 items).</p>
        </div>

        {/* List of History Items */}
        {loading ? (
          <div className="text-center py-5">
            <div className="spinner-border text-chef-orange" role="status">
              <span className="visually-hidden">Loading history...</span>
            </div>
          </div>
        ) : (
          <>
            {/* Desktop & Tablet Table View */}
            <div className="d-none d-md-block bg-white rounded-4 p-3 p-md-4 shadow-sm border">
              <div className="table-responsive">
                <table className="table table-hover align-middle mb-0">
                  <thead className="table-light text-xs text-uppercase tracking-wider text-muted">
                    <tr>
                      <th>Dish Name</th>
                      <th>Servings</th>
                      <th>Spice Level</th>
                      <th>Appliance</th>
                      <th>Creation Date</th>
                      <th className="text-end">Action</th>
                    </tr>
                  </thead>
                  <tbody>
                    {recipeHistory.map((item) => (
                      <tr key={item._id}>
                        <td>
                          <div className="font-label fw-bold text-dark">{item.dishName}</div>
                        </td>
                        <td>{item.servings} people</td>
                        <td>
                          <span className="badge badge-chef-gold">{item.spiceLevel}</span>
                        </td>
                        <td>
                          <span className="badge badge-chef-primary">{item.cookingMethod}</span>
                        </td>
                        <td className="text-xs text-muted">
                          {item.createdAt ? new Date(item.createdAt).toLocaleDateString() : 'Recent'}
                        </td>
                        <td className="text-end">
                          <button
                            className="btn btn-sm btn-outline-chefmate d-inline-flex align-items-center gap-1.5 rounded-pill px-3 fw-semibold"
                            onClick={() => navigate(`/guide?id=${item._id}`)}
                          >
                            <span>Open Guide</span>
                            <ExternalLink size={14} />
                          </button>
                        </td>
                      </tr>
                    ))}

                    {recipeHistory.length === 0 && (
                      <tr>
                        <td colSpan="6" className="text-center py-5 text-muted">
                          No recipe generation history found. Start cooking on the home page!
                        </td>
                      </tr>
                    )}
                  </tbody>
                </table>
              </div>
            </div>

            {/* Mobile Card-Based View */}
            <div className="d-block d-md-none">
              {recipeHistory.length > 0 ? (
                <div className="d-flex flex-column gap-3">
                  {recipeHistory.map((item) => (
                    <div key={item._id} className="card-chefmate p-4 rounded-4 shadow-sm border">
                      <div className="d-flex align-items-center justify-content-between gap-2 mb-3">
                        <h5 className="font-display fw-bold text-dark m-0 fs-6">{item.dishName}</h5>
                        <span className="badge bg-light text-muted border text-xs px-2.5 py-1 rounded-pill fw-medium flex-shrink-0">
                          {item.createdAt ? new Date(item.createdAt).toLocaleDateString() : 'Recent'}
                        </span>
                      </div>

                      <div className="d-flex align-items-center flex-wrap gap-2 mb-3">
                        <span className="badge badge-chef-primary">{item.cookingMethod}</span>
                        <span className="badge badge-chef-gold">{item.spiceLevel} Spice</span>
                        <span className="badge bg-light text-dark border text-xs px-2.5 py-1 rounded-pill fw-semibold d-inline-flex align-items-center gap-1">
                          <Users size={12} className="text-chef-orange" /> {item.servings} people
                        </span>
                      </div>

                      <button
                        className="btn btn-sm btn-outline-chefmate w-100 py-2.5 d-flex align-items-center justify-content-center gap-1.5 rounded-pill font-label fw-bold shadow-xs"
                        onClick={() => navigate(`/guide?id=${item._id}`)}
                      >
                        <span>Open Guide</span>
                        <ExternalLink size={14} />
                      </button>
                    </div>
                  ))}
                </div>
              ) : (
                <div className="card-chefmate p-4 rounded-4 text-center text-muted">
                  No recipe generation history found. Start cooking on the home page!
                </div>
              )}
            </div>
          </>
        )}

      </div>
    </div>
  );
}
