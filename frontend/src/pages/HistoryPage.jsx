import React, { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import { useRecipe } from '../context/RecipeContext';
import { Clock, ExternalLink, Calendar, Flame, Users } from 'lucide-react';

export default function HistoryPage() {
  const navigate = useNavigate();
  const { recipeHistory, fetchRecipeHistory } = useRecipe();
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const load = async () => {
      setLoading(true);
      await fetchRecipeHistory();
      setLoading(false);
    };
    load();
  }, []);

  return (
    <div className="w-100 min-vh-100 pt-4 pb-5">
      <div className="container px-3 px-lg-5">
        
        {/* Header */}
        <div className="mb-4">
          <div className="d-flex align-items-center gap-2 mb-1">
            <Clock size={24} className="text-danger" />
            <h2 className="font-display fw-bold text-dark m-0">Cooking History</h2>
          </div>
          <p className="text-muted text-sm m-0">Recent cooking guides generated by your AI chef assistant.</p>
        </div>

        {/* List of History Items */}
        {loading ? (
          <div className="text-center py-5">
            <div className="spinner-border text-danger" role="status">
              <span className="visually-hidden">Loading history...</span>
            </div>
          </div>
        ) : (
          <div className="bg-white rounded-4 p-3 p-md-4 shadow-sm border">
            <div className="table-responsive">
              <table className="table table-hover align-middle mb-0">
                <thead className="table-light text-xs text-uppercase tracking-wider text-muted">
                  <tr>
                    <th>Dish Name</th>
                    <th>Servings</th>
                    <th>Spice Level</th>
                    <th>Appliance</th>
                    <th>Creation Date</th>
                    <th className="text-end">Action</th>
                  </tr>
                </thead>
                <tbody>
                  {recipeHistory.map((item) => (
                    <tr key={item._id}>
                      <td>
                        <div className="font-label fw-bold text-dark">{item.dishName}</div>
                      </td>
                      <td>{item.servings} people</td>
                      <td>
                        <span className="badge badge-chef-gold">{item.spiceLevel}</span>
                      </td>
                      <td>
                        <span className="badge badge-chef-primary">{item.cookingMethod}</span>
                      </td>
                      <td className="text-xs text-muted">
                        {item.createdAt ? new Date(item.createdAt).toLocaleDateString() : 'Recent'}
                      </td>
                      <td className="text-end">
                        <button
                          className="btn btn-sm btn-outline-danger d-inline-flex align-items-center gap-1.5 rounded-pill px-3 fw-semibold"
                          onClick={() => navigate(`/guide?id=${item._id}`)}
                        >
                          <span>Open Guide</span>
                          <ExternalLink size={14} />
                        </button>
                      </td>
                    </tr>
                  ))}

                  {recipeHistory.length === 0 && (
                    <tr>
                      <td colSpan="6" className="text-center py-5 text-muted">
                        No recipe generation history found. Start cooking on the home page!
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
          </div>
        )}

      </div>
    </div>
  );
}
